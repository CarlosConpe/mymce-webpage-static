const svg = (nombre: string, tam: string) =>
  `<svg class="ico-linea ico-${tam}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${TRAZOS[nombre]}</svg>`;

export function conIconos(html: string): string {
  return html.replace(
    /<i class="(text-xl|icon circle) fa fa-([a-z0-9-]+)"[^>]*><\/i>/g,
    (original, tipo: string, clase: string, pos: number) => {
      let nombre = POR_CLASE[clase];
      if (clase === 'star') {
        // Solo el título: hasta el cierre de la etiqueta o, en las listas, hasta los dos puntos.
        const sigue = html.slice(pos + original.length, pos + original.length + 300).replace(/^(\s|<(?!\/)[^>]+>)+/, '').split(/<\/|:/)[0];
        nombre = POR_TEXTO.find(([re]) => re.test(sigue))?.[1] ?? 'palomita';
      }
      return nombre ? svg(nombre, tipo === 'text-xl' ? 'lista' : 'caja') : original;
    },
  );
}
